function makeSub(
  id: string,
  project_id: string,
  vendor: VendorSeed,
  subcontract_number: string,
  subcontract_status: Subcontractor['subcontract_status'],
  signed_at: string | null,
  closeout_docs_status: Subcontractor['closeout_docs_status'],
  vendor_code: string | null = null,
): Subcontractor {
  return {
    id,
    project_id,
    ...vendor,
    subcontract_number,
    ...subcontractFinancials[id],
    subcontract_status,
    signed_at,
    closeout_docs_status,
    vendor_code,
  };
}

